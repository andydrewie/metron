/** Build the light-first Research Instrument theme from a single JSON source. */
import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../design/tokens.json', import.meta.url);
const destination = new URL('../design/tokens.css', import.meta.url);
const values = JSON.parse(await readFile(source, 'utf8'));
if (values.name !== 'Metron / Research Instrument' || values.mode !== 'light') throw new Error('Unexpected design token package');
const entries = Object.entries(values.cssVariables);
for (const [name, value] of entries) {
  if (!/^--[a-z0-9-]+$/.test(name) || typeof value !== 'string' || /[{};]/.test(value)) throw new Error(`Unsafe design token: ${name}`);
}
const generated = `/* GENERATED by scripts/build-tokens.mjs from design/tokens.json. DO NOT EDIT. */\n:root {\n${entries.map(([k,v]) => `  ${k}: ${v};`).join('\n')}\n  color-scheme: light;\n  font-family: Inter, ui-sans-serif, system-ui, -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif;\n  font-optical-sizing: auto;\n}\n`;
await writeFile(destination, generated);
console.log(`Generated ${entries.length} shared design tokens`);
